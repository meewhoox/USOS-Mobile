#!/usr/bin/env node
/*
 * Dependency-free build.
 *   dist/firefox/        unpacked extension (load via about:debugging or `web-ext run`)
 *   dist/dev-inject.js   everything in one script, for injecting into a page from DevTools
 *                        (no extension APIs: settings live in localStorage only)
 *
 * Usage: node scripts/build.mjs [--watch]
 */
import { readFileSync, writeFileSync, mkdirSync, rmSync, cpSync, readdirSync, watch } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'dist', 'firefox');
const read = (p) => readFileSync(p, 'utf8');

function buildCss() {
  const pagesDir = join(SRC, 'styles', 'pages');
  const pageCss = readdirSync(pagesDir)
    .filter((f) => f.endsWith('.css'))
    .sort()
    .map((f) => `/* ---- pages/${f} ---- */\n${read(join(pagesDir, f))}`);
  const global = [...['themes.css', 'global.css'].map((f) => read(join(SRC, 'styles', f))), ...pageCss].join('\n');
  const components = {};
  const dir = join(SRC, 'styles', 'components');
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.css')).sort()) {
    components[basename(f, '.css')] = read(join(dir, f));
  }
  return { global, components };
}

function buildEarly(css) {
  return `/* generated by scripts/build.mjs — edit src/early.js and src/styles/ */\n(() => {\nconst USM_CSS = ${JSON.stringify(css)};\n${read(join(SRC, 'early.js'))}\n})();\n`;
}

function build() {
  const t0 = Date.now();
  const manifest = JSON.parse(read(join(SRC, 'manifest.json')));
  const css = buildCss();
  const early = buildEarly(css);

  rmSync(OUT, { recursive: true, force: true });
  mkdirSync(OUT, { recursive: true });
  for (const d of ['content', 'popup', '_locales', 'icons']) cpSync(join(SRC, d), join(OUT, d), { recursive: true });
  writeFileSync(join(OUT, 'manifest.json'), JSON.stringify(manifest, null, 2));
  writeFileSync(join(OUT, 'early.js'), early);

  // Dev bundle: early + isolated scripts in manifest order.
  const isolated = manifest.content_scripts.find((c) => c.world !== 'MAIN').js;
  const parts = isolated.map((p) => `/* ---- ${p} ---- */\n${read(join(SRC, p))}`);
  const dev = `/* USOS Mobile dev bundle — generated */\n(() => {\nif (window.__usmDev) { console.info('[USOS Mobile] already injected'); return; }\nwindow.__usmDev = true;\n${early}\n${parts.join('\n')}\n})();\n`;
  writeFileSync(join(ROOT, 'dist', 'dev-inject.js'), dev);

  console.log(`[build] ok in ${Date.now() - t0} ms — ${Object.keys(css.components).length} component sheets`);
}

build();

if (process.argv.includes('--watch')) {
  let timer;
  watch(SRC, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        build();
      } catch (e) {
        console.error('[build] failed:', e.message);
      }
    }, 100);
  });
  console.log('[build] watching src/ …');
}
