#!/usr/bin/env node
/*
 * Dependency-free build of the scripts the app injects into USOSweb.
 *   android/app/src/main/assets/usm.js      early.js (with the CSS) + UI scripts, one bundle,
 *                                           injected at document start on usosweb.polsl.pl
 *   android/app/src/main/assets/usm-cas.js  CAS login page stylesheet as a script (usoscas.polsl.pl)
 *   dist/dev-inject.js                      copy of usm.js for injecting from DevTools
 *
 * Gradle runs this before every app build. Usage: node scripts/build.mjs [--watch]
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, watch } from 'node:fs';
import { join, dirname, basename } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'src');
const ASSETS = join(ROOT, 'android', 'app', 'src', 'main', 'assets');
const DIST = join(ROOT, 'dist');
const read = (p) => readFileSync(p, 'utf8');

/** UI scripts in load order: core first, features in mount order (topbar before submenu/account), main last. */
const SCRIPTS = [
  'content/core.js',
  'content/features/topbar.js',
  'content/features/submenu.js',
  'content/features/bottomnav.js',
  'content/features/account.js',
  'content/features/content.js',
  'content/pages/home.js',
  'content/main.js',
];

function buildCss() {
  const pagesDir = join(SRC, 'styles', 'pages');
  const pageCss = readdirSync(pagesDir)
    .filter((f) => f.endsWith('.css'))
    .sort()
    .map((f) => `/* ---- pages/${f} ---- */\n${read(join(pagesDir, f))}`);
  const global = [...['themes.css', 'global.css'].map((f) => read(join(SRC, 'styles', f))), ...pageCss].join('\n');
  const components = {};
  const dir = join(SRC, 'styles', 'components');
  for (const f of readdirSync(dir).filter((f) => f.endsWith('.css')).sort()) {
    components[basename(f, '.css')] = read(join(dir, f));
  }
  return { global, components };
}

function build() {
  const t0 = Date.now();
  const css = buildCss();
  const early = `(() => {\nconst USM_CSS = ${JSON.stringify(css)};\n${read(join(SRC, 'early.js'))}\n})();`;
  const parts = SCRIPTS.map((p) => `/* ---- ${p} ---- */\n${read(join(SRC, p))}`);
  // addDocumentStartJavaScript runs in every frame of the allowed origin: top frame only.
  const bundle = `/* USOS Mobile — generated by scripts/build.mjs, edit src/ */\n(() => {\nif (window.top !== window || window.__usmLoaded) return;\nwindow.__usmLoaded = true;\n${early}\n${parts.join('\n')}\n})();\n`;

  const casCss = read(join(SRC, 'cas', 'cas.css'));
  const cas = `/* USOS Mobile — CAS login page styles, generated by scripts/build.mjs */\n(() => {\nif (window.top !== window || window.__usmCas) return;\nwindow.__usmCas = true;\nconst style = document.createElement('style');\nstyle.textContent = ${JSON.stringify(casCss)};\nconst place = () => (document.head || document.documentElement)?.append(style);\nif (document.documentElement) place();\nelse new MutationObserver((_, mo) => document.documentElement && (mo.disconnect(), place())).observe(document, { childList: true });\n})();\n`;

  mkdirSync(ASSETS, { recursive: true });
  mkdirSync(DIST, { recursive: true });
  writeFileSync(join(ASSETS, 'usm.js'), bundle);
  writeFileSync(join(ASSETS, 'usm-cas.js'), cas);
  writeFileSync(join(DIST, 'dev-inject.js'), bundle);

  console.log(`[build] ok in ${Date.now() - t0} ms — ${Object.keys(css.components).length} component sheets`);
}

build();

if (process.argv.includes('--watch')) {
  let timer;
  watch(SRC, { recursive: true }, () => {
    clearTimeout(timer);
    timer = setTimeout(() => {
      try {
        build();
      } catch (e) {
        console.error('[build] failed:', e.message);
      }
    }, 100);
  });
  console.log('[build] watching src/ …');
}
